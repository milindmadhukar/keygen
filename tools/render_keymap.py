#!/usr/bin/env python3
"""Draw the ZMK keymap, one picture per layer, into assets/keymap-<layer>.svg.

Uses keymap-drawer (run through uv's `uvx`, so nothing is installed) on firmware/keygen.keymap,
with the physical layout generated by tools/gen_zmk_layout.py, so the thumbs and the knob sit
where they are on the board.
"""
import subprocess, sys, tempfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
KEYMAP = ROOT / "firmware/keygen.keymap"
LAYOUT = ROOT / "firmware/boards/shields/keygen/keygen-layouts.dtsi"
ASSETS = ROOT / "assets"
DRAWER = ["uvx", "--from", "keymap-drawer==0.23.0", "keymap"]

# key positions of the encoder presses, and what turning each knob does per layer
KNOBS = {6: {"Base": "scroll", "Nav": "scroll", "Fn": "scroll"},
         7: {"Base": "volume", "Nav": "page", "Fn": "bright"}}

LABELS = {
    "&esc_ctrl LCTRL ESC": {"t": "Esc", "h": "Ctrl"},
    "&kp LGUI": "Super", "&kp LCTRL": "Ctrl", "&kp LALT": "Alt", "&kp LSHFT": "Shift", "&kp BSPC": "Bksp",
    "&kp RET": "Enter", "&kp SPACE": "Space", "&kp TAB": "Tab", "&kp DEL": "Del", "&kp INS": "Ins", "&kp PSCRN": "PrtSc",
    "&kp CAPS": "Caps Lock", "&caps_word": "Caps Word", "&kp LC(LA(SPACE))": "Dictate",
    "&kp LEFT": "←", "&kp DOWN": "↓", "&kp UP": "↑", "&kp RIGHT": "→",
    "&kp HOME": "Home", "&kp END": "End", "&kp PG_UP": "PgUp", "&kp PG_DN": "PgDn",
    "&kp C_MUTE": "Mute", "&mkp MCLK": "Middle click", "&kp C_PP": "Play", "&kp C_PREV": "Prev", "&kp C_NEXT": "Next",
    "&studio_unlock": "Studio unlock", "&bootloader": "Boot loader", "&sys_reset": "Reset",
    "&out OUT_USB": "USB", "&out OUT_BLE": "BLE", "&out OUT_TOG": "USB/BLE",
    "&bt BT_CLR": "BT clear", **{f"&bt BT_SEL {i}": f"BT {i + 1}" for i in range(5)},
    "&rgb_ug RGB_TOG": "LEDs", "&rgb_ug RGB_EFF": "Effect", "&rgb_ug RGB_HUI": "Hue",
    "&rgb_ug RGB_BRI": "Bright +", "&rgb_ug RGB_BRD": "Bright −",
}

CONFIG = {
    "parse_config": {"raw_binding_map": LABELS, "trans_legend": {"t": "", "type": "trans"}},
    "draw_config": {"dark_mode": "auto", "append_colon_to_layer_header": False},
}

def run(*args, **kw):
    return subprocess.run([*DRAWER, *map(str, args)], check=True, capture_output=True, text=True, **kw).stdout

def main():
    with tempfile.TemporaryDirectory() as d:
        cfg, km = Path(d) / "config.yaml", Path(d) / "keymap.yaml"
        cfg.write_text(yaml.safe_dump(CONFIG, allow_unicode=True))
        keymap = yaml.safe_load(run("-c", cfg, "parse", "-z", KEYMAP))

        for name, keys in keymap["layers"].items():           # label each encoder press as its knob
            for pos, turn in KNOBS.items():
                key = keys[pos]
                key = key if isinstance(key, dict) else {"t": key}
                if name in turn:
                    key["s"] = f"↻ {turn[name]}"
                keys[pos] = key
        km.write_text(yaml.safe_dump(keymap, allow_unicode=True, sort_keys=False))

        for name in keymap["layers"]:
            out = ASSETS / f"keymap-{name.lower()}.svg"
            out.write_text(run("-c", cfg, "draw", "-d", LAYOUT, "-s", name, "--", km))
            print(out.relative_to(ROOT))

if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as e:
        sys.exit(e.stderr)
