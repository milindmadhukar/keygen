#!/usr/bin/env python3
"""Write firmware/boards/shields/keygen/keygen-layouts.dtsi: the ZMK matrix transform and physical
layout, from the same Redox KLE and key table the PCB is placed from.

Key positions (the order of every keymap layer) run left to right, top to bottom:
number row (with the encoder press between the halves), top, home, bottom, the extra row, the
thumb cluster's 1u top row, then its bottom row (1.25u, 1.5u, 1.5u on each half).
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import gen_pcb as p
import gen_schematic as g

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "firmware/boards/shields/keygen/keygen-layouts.dtsi"
COLS = 7                      # per half; the right half's columns are offset by this in the transform

L, R = "left", "right"
ORDER = [
    [(L, 0, c) for c in range(6)] + [(R, 0, 6)] + [(R, 0, c) for c in range(5, -1, -1)],
    *[[(L, r, c) for c in range(6)] + [(R, r, c) for c in range(5, -1, -1)] for r in (1, 2, 3)],
    [(L, 4, c) for c in range(4)] + [(R, 4, c) for c in range(3, -1, -1)],
    [(L, 3, 6), (L, 2, 6), (R, 2, 6), (R, 3, 6)],
    [(L, 4, 4), (L, 4, 5), (L, 4, 6), (R, 4, 6), (R, 4, 5), (R, 4, 4)],
]

def kle_keys():
    """(side, row, col) -> KLE key dict (x, y, w, h, r, rx, ry in key units / degrees)."""
    out = {KLE_POS: k for i, k in enumerate(p.parse_kle(p.KLE)) if (KLE_POS := p.KLE_MAP.get(i))}
    # the encoder press: a 1u key centred on the encoder shaft
    sx, sy = p.ENCODER_SHAFT
    side, (r, c) = next(iter(g.ENCODER_POS.items()))
    out[(side, r, c)] = dict(x=sx / p.U - 0.5, y=sy / p.U - 0.5, w=1, h=1, r=0, rx=0, ry=0)
    return out

def attrs(k):
    v = [round(k[n] * 100) for n in ("w", "h", "x", "y", "r", "rx", "ry")]
    return "<&key_physical_attrs " + " ".join(f"{(f'({n})' if n < 0 else n):>6}" for n in v) + ">"

def main():
    keys = kle_keys()
    flat = [pos for row in ORDER for pos in row]
    expected = {(s, r, c) for s in (L, R) for r, c, *_ in g.KEYS[s]} | {(s, *rc) for s, rc in g.ENCODER_POS.items()}
    assert len(flat) == len(set(flat)) and set(flat) == expected, "ORDER must cover every key once"

    rc = lambda s, r, c: f"RC({r},{c + (COLS if s == R else 0)})"
    rows = ["        " + " ".join(f"{rc(*pos):<8}" for pos in row).rstrip() for row in ORDER]
    phys = [("= " if i == 0 else ", ") + attrs(keys[pos]) for i, pos in enumerate(flat)]

    OUT.write_text(f"""\
/*
 * Generated by tools/gen_zmk_layout.py from the Redox KLE in tools/gen_pcb.py - edit the script.
 * {len(flat)} key positions: {", ".join(str(len(r)) for r in ORDER)} per row
 * (number row with the encoder press, top, home, bottom, extra row, thumb top, thumb bottom).
 */

#include <dt-bindings/zmk/matrix_transform.h>
#include <physical_layouts.dtsi>

/ {{
    default_transform: keymap_transform_0 {{
        compatible = "zmk,matrix-transform";
        columns = <{2 * COLS}>;
        rows = <5>;
        map = <
{chr(10).join(rows)}
        >;
    }};

    keygen_layout: keygen_layout {{
        compatible = "zmk,physical-layout";
        display-name = "Keygen";
        transform = <&default_transform>;

        keys  //                        w      h      x      y    rot     rx     ry
            {(chr(10) + "            ").join(phys)}
            ;
    }};
}};
""")
    print(f"{OUT.relative_to(ROOT)}: {len(flat)} key positions")

if __name__ == "__main__":
    main()
